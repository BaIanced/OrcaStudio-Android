package app.orcaandroid.net

import android.net.Uri
import android.util.Base64
import java.io.File

/**
 * 3D Filament Profiles (3dfilamentprofiles.com): filament database, spool inventory and print log.
 * It has no API; the app shows the site in the Models tab and hands prints over the way the site's
 * own slicer print logger does (MarksMakerSpace/filament-profiles, tools/slicer-print-log): a few
 * G-code comment lines go into a /my/print/log URL, where the user picks the spools and subtracts.
 */
object FilamentProfiles {
    const val HOME = "https://3dfilamentprofiles.com/"

    // The logger's allow-list (the site decodes these; order kept for a stable payload).
    private val LINE_PREFIXES = listOf(
        "; filament used [g]",
        "; filament used [mm]",
        "; total filament weight [g]",
        "; total filament length [mm]",
        "; total filament used [g]",
        "; filament:",
        "; filament_type =",
        "; filament_vendor =",
        "; filament_colour =",
        "; filament_settings_id =",
        "; printer_model =",
        "; printer_settings_id =",
        "; estimated printing time",
        "; model printing time",
        "; generated by",
        "; BambuStudio",
        "; OrcaSlicer",
        "; PrusaSlicer",
    )
    private const val MAX_LINE_LENGTH = 400
    private const val MAX_PAYLOAD_BYTES = 16 * 1024

    /**
     * The print log page for [gcode] ([fileName] as the site shows it, [plate] 1-based), or null when
     * the G-code has no filament usage comments. Reads the whole file: the config lines are at its end.
     */
    fun printLogUrl(gcode: File, fileName: String, plate: Int): String? {
        val found = HashMap<String, String>()
        gcode.bufferedReader().useLines { lines ->
            for (line in lines) {
                if (!line.startsWith(";")) continue
                for (prefix in LINE_PREFIXES)
                    if (prefix !in found && line.startsWith(prefix)) found[prefix] = line.take(MAX_LINE_LENGTH)
                if (found.size == LINE_PREFIXES.size) break
            }
        }
        if (LINE_PREFIXES.none { it in found && it.contains("[g]") }) return null
        var payload = LINE_PREFIXES.mapNotNull { found[it] }.joinToString("\n").toByteArray()
        if (payload.size > MAX_PAYLOAD_BYTES) payload = payload.copyOf(MAX_PAYLOAD_BYTES)
        val data = Base64.encodeToString(payload, Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP)
        return "${HOME}my/print/log?v=1&f=${Uri.encode(fileName)}&p=$plate&d=$data"
    }
}
